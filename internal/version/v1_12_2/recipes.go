package v1_12_2

// The 1.12.2 crafting recipe registry.
//
// 1.12.2 keeps the recipes in JSON files: the server reads
// `assets/minecraft/recipes/<name>.json` out of its own jar and
// registers every file under the key `minecraft:<name>`, so the
// name of a recipe is the name of the file it lives in. On top of
// those there are eleven recipes the server builds in code, which
// are the ones it refuses to hand out (see specialRecipeKeys).
//
// The registry holds 432 recipes. Their names are the ones the
// server answers with, which is the display name of the item the
// recipe produces -- not the name of the recipe itself:
// `minecraft:stone_slab` produces a stone slab, and the server
// calls it "Stone Slab".
//
// (Measured on a real Paper 1.12.2: `recipe give <player> <name>`
// answers "Successfully given <player> the recipe for <name>".)
type recipeEntry struct {
	// key is the recipe id, e.g. "minecraft:stone_slab".
	key string
	// name is what the server calls the recipe: the display name
	// of the item the recipe produces.
	name string
}

