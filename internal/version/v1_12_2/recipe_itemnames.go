// The names 1.12.2 shows for the items, by their registry name.
//
// The names come from the language file of the server. An item is named
// after the key "<unlocalized name>.name"; a block item after
// "tile.<name>.name". The unlocalized name of a block item carries its
// variant, so the stone slab is "tile.stoneSlab.stone" while its key is
// "tile.stoneSlab.name" -- the table holds the name the server prints,
// which is the one of the key.
//
