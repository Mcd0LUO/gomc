// ItemDisplayName returns the name 1.12.2 gives an entity that carries
// the item, and whether the server knows the item at all.
//
// The name of the item is the one the item stack carries, and 1.12.2
// reads it as a `MinecraftKey`: the namespace defaults to "minecraft"
// and the name is lower-cased.
func ItemDisplayName(item string) (string, bool) {
	namespace, key := EntityTypeKey(item)
	if namespace != "minecraft" {
		return "", false
	}
	name, ok := itemDisplayNames[key]
	return name, ok
}

// IsKnownItem reports whether 1.12.2 knows an item of that name.
//
// The blocks that have no item of their own -- fire, water, the
// redstone wire and the like -- are not items, so an item entity
// cannot be built from them either.
func IsKnownItem(item string) bool {
	_, ok := ItemDisplayName(item)
	return ok
}
