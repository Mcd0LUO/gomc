// IsKnownBlock reports whether 1.12.2 knows a block of that name.
//
// The name is read as a `MinecraftKey`: the namespace defaults to
// "minecraft" and the name is lower-cased. The colon only separates a
// namespace when it is neither the first nor the second character, so
// "stone", "minecraft:stone", ":stone" and "a:stone" all name the same
// block, while "foo:stone" names a block of another namespace and
// "stone:1" names the key "1" of the namespace "stone".
func IsKnownBlock(name string) bool {
	namespace, key := EntityTypeKey(name)
	if namespace != "minecraft" {
		return false
	}
	return knownBlockNames[key]
}
