// Command blockstates turns the dump of the 1.12.2 block states into the Go
// table of the v1_12_2 package.
//
// The dump is made by DumpStates.java, which runs the block registry of the
// real 1.12.2 server jar and writes one JSON object per block. The table it
// produces is the list of the blocks that have properties, the properties
// they have, the values those properties take and the data value every
// combination of them has.
//
//	go run ./tools/blockstates -in tools/blockstates/states.jsonl \
//	    -out internal/version/v1_12_2/blockstates_table.go
//
// The dump in the repository is the one of the server jar
// D:\game\McServer\1.12.2\cache\patched_1.12.2.jar; see docs/DEV.md.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

// dumpBlock is one block of the dump.
type dumpBlock struct {
	Block       string     `json:"block"`
	Props       []dumpProp `json:"props"`
	Default     []int32    `json:"default"`
	DefaultMeta int        `json:"defaultMeta"`
	Metas       []int      `json:"metas"`
	// Legacy is the translation of a data value: the data value of the
	// state that `fromLegacyData(n)` gives. A -1 means the block has no
	// such state, so the data value is refused.
	Legacy []int `json:"legacy"`
}

// dumpProp is one property of a block.
type dumpProp struct {
	Name   string   `json:"name"`
	Kind   string   `json:"kind"`
	Values []string `json:"values"`
}

func main() {
	in := flag.String("in", "tools/blockstates/states.jsonl", "the dump to read")
	out := flag.String("out", "internal/version/v1_12_2/blockstates_table.go", "the Go file to write")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		fail(err)
	}
	var blocks []dumpBlock
	for i, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		var b dumpBlock
		if err := json.Unmarshal([]byte(line), &b); err != nil {
			fail(fmt.Errorf("line %d: %w", i+1, err))
		}
		blocks = append(blocks, b)
	}
	sort.Slice(blocks, func(i, j int) bool { return blocks[i].Block < blocks[j].Block })

	src, err := generate(blocks)
	if err != nil {
		fail(err)
	}
	formatted, err := format.Source(src)
	if err != nil {
		fail(fmt.Errorf("the generated file is not valid Go: %w", err))
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		fail(err)
	}
	fmt.Printf("wrote %s: %d blocks\n", *out, len(blocks))
}

// generate writes the Go table.
func generate(blocks []dumpBlock) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by tools/blockstates. DO NOT EDIT.
//
// The block states of 1.12.2: the properties every block has, the values
// those properties take and the data value of every combination of them.
//
// The table holds every block of the registry, also the ones without
// properties: their default state is the data value 0.
//
// The table is dug out of the real 1.12.2 server jar, see tools/blockstates.
package v1_12_2

// blockStateTables holds the state table of every block.
//
// The blocks that have no properties are in here too: the "legacy" array
// of theirs says that every data value but the first is out of range.
var blockStateTables = map[string]*blockStateTable{
`)
	for _, blk := range blocks {
		if err := checkBlock(blk); err != nil {
			return nil, fmt.Errorf("%s: %w", blk.Block, err)
		}
		fmt.Fprintf(&b, "\t%q: {\n", blk.Block)
		b.WriteString("\t\tprops: []blockStateProp{\n")
		for _, p := range blk.Props {
			fmt.Fprintf(&b, "\t\t\t{name: %q, kind: %s", p.Name, kindConst(p.Kind))
			if p.Kind == "integer" {
				min := 0
				fmt.Sscanf(p.Values[0], "%d", &min)
				fmt.Fprintf(&b, ", min: %d", min)
			}
			b.WriteString(", values: []string{")
			for i, v := range p.Values {
				if i > 0 {
					b.WriteString(", ")
				}
				fmt.Fprintf(&b, "%q", v)
			}
			b.WriteString("}},\n")
		}
		b.WriteString("\t\t},\n")
		b.WriteString("\t\tdefaults: []int32{")
		for i, d := range blk.Default {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%d", d)
		}
		b.WriteString("},\n")
		b.WriteString("\t\tmetas: []uint8{")
		for i, m := range blk.Metas {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%d", m)
		}
		b.WriteString("},\n")
		b.WriteString("\t\tlegacy: [16]int8{")
		for i, m := range blk.Legacy {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%d", m)
		}
		b.WriteString("},\n")
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

// checkBlock makes sure the dump is consistent before it is turned into a
// table: the number of data values has to be the number of combinations of
// the values of the properties, and the default state has to be one of them.
func checkBlock(blk dumpBlock) error {
	count := 1
	for _, p := range blk.Props {
		if len(p.Values) == 0 {
			return fmt.Errorf("property %q has no value", p.Name)
		}
		count *= len(p.Values)
	}
	if count != len(blk.Metas) {
		return fmt.Errorf("%d combinations but %d data values", count, len(blk.Metas))
	}
	if len(blk.Default) != len(blk.Props) {
		return fmt.Errorf("%d default values for %d properties", len(blk.Default), len(blk.Props))
	}
	off := 0
	for k, d := range blk.Default {
		if d < 0 || int(d) >= len(blk.Props[k].Values) {
			return fmt.Errorf("default value %d of property %q is out of range", d, blk.Props[k].Name)
		}
		off = off*len(blk.Props[k].Values) + int(d)
	}
	if blk.Metas[off] != blk.DefaultMeta {
		return fmt.Errorf("the default state has the data value %d, the table says %d",
			blk.DefaultMeta, blk.Metas[off])
	}
	for _, m := range blk.Metas {
		if m < 0 || m > 15 {
			return fmt.Errorf("the data value %d is out of range", m)
		}
	}
	if len(blk.Legacy) != 16 {
		return fmt.Errorf("%d data value translations, want 16", len(blk.Legacy))
	}
	for n, m := range blk.Legacy {
		if m < -1 || m > 15 {
			return fmt.Errorf("the translation of the data value %d is %d", n, m)
		}
	}
	return nil
}

// kindConst returns the Go constant of a kind of the dump.
func kindConst(kind string) string {
	switch kind {
	case "integer":
		return "stateKindInt"
	default:
		return "stateKindName"
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "error:", err)
	os.Exit(1)
}
